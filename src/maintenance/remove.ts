/**
 * 「把一个缓存文件拿掉」这一步的**唯一**实现。
 *
 * ## 只有一种方式：直接删除
 *
 * `Vault.delete`，磁盘空间**立刻**释放。不存在"移入回收站"这个备选 ——
 * 它被**有意去掉**了，理由是这个功能存在的目的：
 *
 * > 上限要解决的是**空间**。回收站不释放物理空间 —— 文件离开了 vault
 * >（同步与备份的体积确实变小了），但磁盘上那份还占着，于是表现成
 * > "设了缓存上限，磁盘还是满的"，而想真正释放还得再手动清空回收站，
 * > 没人会记得做这件事。留着这个选项等于让功能的一半失效，且症状不可见。
 *
 * 所以那不是"少一个选择"，而是**去掉一个自相矛盾的选项**：
 * 用户设上限时期待的是"空间被腾出来"，而这个选项做不到。
 *
 * ## 为什么删得干脆是可以的
 *
 * 因为这里删的**只是缓存副本**：笔记里存的始终是**远端地址**（从没被改写），
 * 所以被删掉的副本下次看到那张图时会**自动重新下载**。
 * 代价是"重新拉一遍"，**不是丢数据** —— 可恢复性由**重新下载**提供，
 * 不必由回收站提供。
 *
 * ⚠️ 这条不适用于**用户自己的文件**：上传后不留本地副本（`localCopy: "trash"`）
 * 那条路径删的是用户的原始附件，它**仍然走回收站**（见 `core/ingest.ts`）。
 * 两者的区别不是"危险程度"，而是"能不能重新拿到" —— 缓存副本能，用户的图不能。
 *
 * ## ⚠️ 绝不用 `adapter.remove`
 *
 * 它是底层删除，绕开的是**宿主的文件索引**（不是"回收站设置"）。
 * 那样删掉之后，文件在磁盘上没了，而宿主的 `getFiles()` 仍然认得它 ——
 * 留下"看得见、读不到"的幽灵条目，渲染层还会照着它去换 `app://` 地址然后加载失败。
 *
 * 换句话说：**要删就用 `vault.delete`，而不是绕开宿主自己删。**
 * 前者是"我们告诉宿主把这个文件彻底删掉"，后者是"我们背着宿主改了它的地盘"。
 *
 * ## 为什么这仍然值得单独一个模块
 *
 * 它现在的实现只有一行，但它是全库**唯一**真的会删文件的地方，而且两条调用路径
 * （后台自动淘汰、用户确认后的清理命令）都从这里过。这个模块承载的是三件事，
 * 都不是"多一层函数"：
 *
 * 1. **一处定义**，所以两个入口不可能分叉 —— 分叉的症状是"我清理了缓存，空间却没变"；
 * 2. **调用方该守的纪律**（先复核路径在缓存目录内、先拿到删除凭据）写在这里的注释里，
 *    读这行代码的人不必去翻两个调用点；
 * 3. **社区 lint 的例外只开在这一个文件上**（见下）。
 *
 * ⚠️ `obsidianmd/prefer-file-manager-trash-file` 会对下面那行 `vault.delete` 报警
 *（它的立场是"删除一律走回收站"）。这条规则已经**有意**在这个文件上关掉，
 * 理由写在 `eslint.config.mts` 里紧挨着那一条的位置 —— 只关这一个文件，
 * 其余地方若冒出 `vault.delete` 仍会被报出来（`test-remove.mjs` 还有一条静态守卫盯着）。
 */

import type { App, TAbstractFile } from "obsidian";

/**
 * 删掉一个缓存文件。
 *
 * 调用方负责**先确认删除凭据**（宿主的文件索引可能滞后于磁盘，
 * 那时 `getAbstractFileByPath` 返回 null）并复核路径在缓存目录内 ——
 * 那些判断在 `run.ts` 里，因为只有它知道"什么算可以删的"。
 *
 * ## ⚠️ 这个 promise 必须被 await
 *
 * 调用方紧接着就要**摘掉索引记录**。不等删除完成的话，记录会先被摘掉而文件
 * 还留在磁盘上 —— 渲染层于是以为"本地没有副本"，又去下载一个**其实还在**的文件。
 */
export async function removeCacheFile(app: App, file: TAbstractFile): Promise<void> {
	// 官方文档原话是 "Deletes the file completely" —— 不经回收站，空间立刻释放。
	// 第二个参数 `force` 的语义是"文件夹里有隐藏子项时也照删"，对单个文件没有意义，
	// 传它只会让后来的人把这行误读成"强制永久删除"。
	await app.vault.delete(file);
}
