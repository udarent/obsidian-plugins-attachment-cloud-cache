/**
 * 「用户可见提示」的统一出口 —— 核心层与维护层共用这一个。
 *
 * ## 它解决的问题
 *
 * 这些层**不知道当前界面是中文还是英文**（那是 `main.ts` 与 `i18n.ts` 的事）。
 * 于是每一句提示都只有两种写法：
 *
 * | 写法 | 结果 |
 * |---|---|
 * | 在这里硬编码一句中文 | ⚠️ 英文用户在那**唯一一次**提示里看到中文字符 |
 * | 在这里调 `t("键")` | ✅ 但这一层拿不到 `t`（它由接线层注入） |
 *
 * 所以约定是：**键在这一层选，文字由接线层给**。这一层只说"要哪一句"，
 * 于是中英两套文案全在 `i18n.ts` 一处，而这一层的行为与语言无关、能被套件穷举。
 *
 * ## ⚠️ 省略 `t` 时退回**键名**，绝不退回中文
 *
 * 退回中文会让"调用方忘了注入 `t`"变成一个**只有英文用户看得见**的缺陷，
 * 而它不报错、不抛异常（2026-10-11 实测：`core/ingest.ts` 与 `core/download.ts`
 * 里就是这样各留了几条中文兜底）。退回键名则是"一眼看得出来没接线" ——
 * 与 `core/external-cache.ts` 里那条 `say` 的既有约定一致。
 *
 * ## 纪律：**没有 `notify` 就什么都不做**
 *
 * 每一层都把 `notify` 声明为可选（批处理与静默路径故意不出声），
 * 所以这里的第一件事是"问一下有没有出口"。这样调用点不必层层判空。
 */

/** 一个"能对用户说话"的依赖面。各模块的 deps 直接 `extends` 它。 */
export interface NotifySink {
	/** 用户可见的提示。**省略 = 这一层不出声**（例如批量命令里避免刷屏）。 */
	notify?: (message: string) => void;
	/**
	 * 文案解析（`键 → 该语言的字符串`），由接线层注入（生产上就是插件实例的 `t`）。
	 *
	 * ⚠️ 省略时退回键名（只有测试会这样）—— 见文件头注释。
	 */
	t?: (key: string, params?: Record<string, unknown>) => string;
}

/**
 * 说一句用户可见的话。
 *
 * ⚠️ 它**绝不抛错**，也不做任何判断：调用它的时刻几乎都是"文件已经安全落盘、
 * 只是后续某一步没走完"（指标落盘失败、搬移失败、缓存目录没配），
 * 那种时刻弹错会把一次可解释的降级变成一次崩溃。
 */
export function notifyUser(deps: NotifySink, key: string, params?: Record<string, unknown>): void {
	if (!deps.notify) return;
	deps.notify(deps.t ? deps.t(key, params) : key);
}
